CREATE TABLE vehicle (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    insured_id     BIGINT       NOT NULL,
    brand          VARCHAR(100) NOT NULL,
    model          VARCHAR(100) NOT NULL,
    year           INTEGER      NOT NULL,
    license_plate  VARCHAR(20)  NOT NULL,
    version        BIGINT       NOT NULL DEFAULT 0,
    created_at     TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at     TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_vehicle_license_plate UNIQUE (license_plate),
    CONSTRAINT fk_vehicle_insured FOREIGN KEY (insured_id) REFERENCES insured (id) ON DELETE CASCADE
);

CREATE INDEX idx_vehicle_insured_id ON vehicle (insured_id);

CREATE TABLE vehicle_catalog (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    make           VARCHAR(100) NOT NULL,
    model          VARCHAR(100) NOT NULL,
    model_version  VARCHAR(150) NOT NULL,
    vehicle_type   VARCHAR(20)  NOT NULL,
    version        BIGINT       NOT NULL DEFAULT 0,
    created_at     TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at     TIMESTAMP WITH TIME ZONE NOT NULL,
    -- Only the full triple is unique: one make/model has many versions.
    CONSTRAINT uk_vehicle_catalog_make_model_version UNIQUE (make, model, model_version),
    CONSTRAINT ck_vehicle_catalog_vehicle_type
        CHECK (vehicle_type IN ('CAR', 'MOTORCYCLE', 'SUV', 'PICKUP', 'VAN', 'TRUCK', 'BUS'))
);

CREATE INDEX idx_vehicle_catalog_type_make_model ON vehicle_catalog (vehicle_type, make, model);

CREATE TABLE vehicle_valuation (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    catalog_id  BIGINT         NOT NULL,
    year        INTEGER        NOT NULL,
    value       NUMERIC(14, 2) NOT NULL,
    valid_from  DATE           NOT NULL,
    version     BIGINT         NOT NULL DEFAULT 0,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_vehicle_valuation_catalog_year_valid_from UNIQUE (catalog_id, year, valid_from),
    CONSTRAINT ck_vehicle_valuation_year CHECK (year >= 1900),
    CONSTRAINT ck_vehicle_valuation_value CHECK (value > 0),
    CONSTRAINT fk_vehicle_valuation_catalog FOREIGN KEY (catalog_id) REFERENCES vehicle_catalog (id) ON DELETE CASCADE
);

-- The old free-text vehicle table is replaced by insured_vehicle, which points to a catalog valuation.
-- Existing rows were dev-only data and are discarded.
DROP TABLE vehicle;

CREATE TABLE insured_vehicle (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    insured_id     BIGINT      NOT NULL,
    valuation_id   BIGINT      NOT NULL,
    license_plate  VARCHAR(20) NOT NULL,
    version        BIGINT      NOT NULL DEFAULT 0,
    created_at     TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at     TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_insured_vehicle_license_plate UNIQUE (license_plate),
    CONSTRAINT fk_insured_vehicle_insured FOREIGN KEY (insured_id) REFERENCES insured (id) ON DELETE CASCADE,
    CONSTRAINT fk_insured_vehicle_valuation FOREIGN KEY (valuation_id) REFERENCES vehicle_valuation (id) ON DELETE RESTRICT
);

CREATE INDEX idx_insured_vehicle_insured_id ON insured_vehicle (insured_id);
CREATE INDEX idx_insured_vehicle_valuation_id ON insured_vehicle (valuation_id);

-- Quotation parameters per vehicle type. One row per type.
-- civil_liability_base_amount is the fixed base premium for civil liability coverage. It does not depend on the
-- vehicle valuation. In USD, like the vehicle valuations (converted from ARS at about 1500 ARS per USD).
-- Rates are fractions applied to the vehicle valuation: 0.0040 = 0.40%.
CREATE TABLE quotation_vehicle_parameter (
    id                           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vehicle_type                 VARCHAR(20)    NOT NULL,
    civil_liability_base_amount  NUMERIC(14, 2) NOT NULL,
    theft_rate                   NUMERIC(6, 4)  NOT NULL,
    damage_rate                  NUMERIC(6, 4)  NOT NULL,
    CONSTRAINT uk_quotation_vehicle_parameter_vehicle_type UNIQUE (vehicle_type),
    CONSTRAINT ck_quotation_vehicle_parameter_vehicle_type
        CHECK (vehicle_type IN ('CAR', 'MOTORCYCLE', 'SUV', 'PICKUP', 'VAN', 'TRUCK', 'BUS')),
    CONSTRAINT ck_quotation_vehicle_parameter_civil_liability_base_amount CHECK (civil_liability_base_amount > 0),
    CONSTRAINT ck_quotation_vehicle_parameter_theft_rate CHECK (theft_rate > 0 AND theft_rate < 1),
    CONSTRAINT ck_quotation_vehicle_parameter_damage_rate CHECK (damage_rate > 0 AND damage_rate < 1)
);


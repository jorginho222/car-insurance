-- Quotation factors per driver age range: multipliers applied to the civil liability and damage coverage prices.
-- Ranges are inclusive on both ends (21-24 covers 21 and 24). A NULL max_age means no upper limit.
-- Ranges cannot overlap (exclusion constraint) or leave gaps, and the last one must be open (deferred trigger).
CREATE TABLE quotation_driver_age_factor (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    min_age          INTEGER       NOT NULL,
    max_age          INTEGER,
    civil_liability  NUMERIC(5, 2) NOT NULL,
    damage           NUMERIC(5, 2) NOT NULL,
    CONSTRAINT ck_quotation_driver_age_factor_min_age CHECK (min_age >= 0),
    CONSTRAINT ck_quotation_driver_age_factor_max_age CHECK (max_age IS NULL OR max_age >= min_age),
    CONSTRAINT ck_quotation_driver_age_factor_civil_liability CHECK (civil_liability > 0),
    CONSTRAINT ck_quotation_driver_age_factor_damage CHECK (damage > 0),
    CONSTRAINT ex_quotation_driver_age_factor_no_overlap
        EXCLUDE USING gist (int4range(min_age, max_age, '[]') WITH &&)
);

-- Checks the whole table: each range starts right after the previous one ends, and the last range is open.
CREATE FUNCTION check_quotation_driver_age_factor_ranges() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    IF EXISTS (
        SELECT 1
        FROM (
            SELECT min_age,
                   LAG(min_age) OVER (ORDER BY min_age) AS previous_min_age,
                   LAG(max_age) OVER (ORDER BY min_age) AS previous_max_age
            FROM quotation_driver_age_factor
        ) ranges
        WHERE previous_min_age IS NOT NULL
          AND (previous_max_age IS NULL OR min_age <> previous_max_age + 1)
    ) THEN
        RAISE EXCEPTION 'quotation_driver_age_factor ranges must not leave gaps'
            USING ERRCODE = 'check_violation';
    END IF;

    IF EXISTS (
        SELECT 1
        FROM quotation_driver_age_factor
        WHERE min_age = (SELECT MAX(min_age) FROM quotation_driver_age_factor)
          AND max_age IS NOT NULL
    ) THEN
        RAISE EXCEPTION 'the last quotation_driver_age_factor range must have no max_age'
            USING ERRCODE = 'check_violation';
    END IF;

    RETURN NULL;
END;
$$;

-- Deferred to commit, so a change of several rows (e.g. splitting a range) is checked only once it is complete.
CREATE CONSTRAINT TRIGGER trg_quotation_driver_age_factor_ranges
    AFTER INSERT OR UPDATE OR DELETE ON quotation_driver_age_factor
    DEFERRABLE INITIALLY DEFERRED
    FOR EACH ROW EXECUTE FUNCTION check_quotation_driver_age_factor_ranges();


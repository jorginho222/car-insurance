-- Quotation factors per zone: multipliers applied to the price of each coverage. One row per zone.
CREATE TABLE quotation_factor (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    zone_id          BIGINT        NOT NULL,
    civil_liability  NUMERIC(5, 2) NOT NULL,
    theft            NUMERIC(5, 2) NOT NULL,
    damage           NUMERIC(5, 2) NOT NULL,
    CONSTRAINT uk_quotation_factor_zone UNIQUE (zone_id),
    CONSTRAINT fk_quotation_factor_zone FOREIGN KEY (zone_id) REFERENCES zone (id) ON DELETE RESTRICT,
    CONSTRAINT ck_quotation_factor_civil_liability CHECK (civil_liability > 0),
    CONSTRAINT ck_quotation_factor_theft CHECK (theft > 0),
    CONSTRAINT ck_quotation_factor_damage CHECK (damage > 0)
);

INSERT INTO quotation_factor (zone_id, civil_liability, theft, damage)
SELECT z.id, v.civil_liability, v.theft, v.damage
FROM (VALUES
    ('GBA',                           1.20, 1.60, 1.10),
    ('CABA',                          1.15, 1.30, 1.05),
    ('Ciudades grandes del interior', 1.00, 1.00, 1.25),
    ('Resto del país',                0.85, 0.70, 0.90)
) AS v (zone, civil_liability, theft, damage)
JOIN zone z ON z.name = v.zone;

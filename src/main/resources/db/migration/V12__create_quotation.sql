-- Stored quotations. Each one quotes every plan for a vehicle valuation, a locality and a driver.
-- status: QUOTED when issued, ACCEPTED when a policy is created from it, EXPIRED once valid_until has passed
-- (valid_until is the last valid day). A nightly job moves QUOTED rows past valid_until to EXPIRED.
CREATE TABLE quotation (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    quoted_at          TIMESTAMP WITH TIME ZONE NOT NULL,
    valid_until        DATE        NOT NULL,
    status             VARCHAR(20) NOT NULL,
    valuation_id       BIGINT      NOT NULL,
    locality_id        BIGINT      NOT NULL,
    driver_birth_date  DATE        NOT NULL,
    driver_age         INTEGER     NOT NULL,
    version            BIGINT      NOT NULL DEFAULT 0,
    CONSTRAINT ck_quotation_status CHECK (status IN ('QUOTED', 'ACCEPTED', 'EXPIRED')),
    CONSTRAINT ck_quotation_driver_age CHECK (driver_age >= 18),
    CONSTRAINT fk_quotation_valuation FOREIGN KEY (valuation_id) REFERENCES vehicle_valuation (id) ON DELETE RESTRICT,
    CONSTRAINT fk_quotation_locality FOREIGN KEY (locality_id) REFERENCES locality (id) ON DELETE RESTRICT
);

CREATE INDEX idx_quotation_status_valid_until ON quotation (status, valid_until);
CREATE INDEX idx_quotation_valuation_id ON quotation (valuation_id);
CREATE INDEX idx_quotation_locality_id ON quotation (locality_id);

-- One row per plan of a quotation. payment_options holds the 1-payment and 12-installment breakdowns.
CREATE TABLE quotation_plan (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    quotation_id     BIGINT         NOT NULL,
    name             VARCHAR(30)    NOT NULL,
    net_premium      NUMERIC(14, 2) NOT NULL,
    payment_options  JSONB          NOT NULL,
    CONSTRAINT uk_quotation_plan_quotation_name UNIQUE (quotation_id, name),
    CONSTRAINT ck_quotation_plan_name CHECK (name IN ('CIVIL_LIABILITY', 'THIRD_PARTY_EXTENDED', 'FULL_COVERAGE')),
    CONSTRAINT fk_quotation_plan_quotation FOREIGN KEY (quotation_id) REFERENCES quotation (id) ON DELETE CASCADE
);

-- The coverages of a plan (value objects), kept in plan order by position.
CREATE TABLE quotation_plan_coverage (
    quotation_plan_id  BIGINT         NOT NULL,
    position           INTEGER        NOT NULL,
    type               VARCHAR(20)    NOT NULL,
    premium            NUMERIC(14, 2) NOT NULL,
    CONSTRAINT pk_quotation_plan_coverage PRIMARY KEY (quotation_plan_id, position),
    CONSTRAINT ck_quotation_plan_coverage_type CHECK (type IN ('LIABILITY', 'THEFT', 'DAMAGE')),
    CONSTRAINT fk_quotation_plan_coverage_plan
        FOREIGN KEY (quotation_plan_id) REFERENCES quotation_plan (id) ON DELETE CASCADE
);

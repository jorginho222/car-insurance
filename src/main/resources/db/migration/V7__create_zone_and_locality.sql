-- A postal code is not unique: one postal code can cover many localities, even in different provinces.
CREATE TABLE locality (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name         VARCHAR(100) NOT NULL,
    province     VARCHAR(100) NOT NULL,
    postal_code  VARCHAR(10)  NOT NULL,
    zone_id      BIGINT       NOT NULL,
    CONSTRAINT uk_locality_province_name_postal_code UNIQUE (province, name, postal_code),
    CONSTRAINT fk_locality_zone FOREIGN KEY (zone_id) REFERENCES zone (id) ON DELETE RESTRICT
);

CREATE INDEX idx_locality_postal_code ON locality (postal_code);
CREATE INDEX idx_locality_zone_id ON locality (zone_id);

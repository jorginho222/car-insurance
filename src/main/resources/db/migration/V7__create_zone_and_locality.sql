-- Zones group localities for pricing. Each zone will get its own quotation factors later.
CREATE TABLE zone (
    id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name  VARCHAR(50) NOT NULL,
    CONSTRAINT uk_zone_name UNIQUE (name)
);


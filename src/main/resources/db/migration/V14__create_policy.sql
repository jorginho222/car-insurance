-- Insureds and their vehicles are now created only when a policy is issued. Existing rows are development data
-- without the new vehicle fields, so they are removed (vehicles cascade).
DELETE FROM insured;

-- The insured's address uses the names of the locality it comes from (the quotation's locality).
ALTER TABLE insured RENAME COLUMN city TO locality;
ALTER TABLE insured RENAME COLUMN state TO province;

-- Each policy creates its own vehicle row, so the same plate can appear more than once (e.g. a renewal). A plate
-- can't have two policies with overlapping periods; that rule is checked when issuing the policy.
-- license_plate is stored upper-cased without spaces or hyphens.
ALTER TABLE insured_vehicle
    DROP CONSTRAINT uk_insured_vehicle_license_plate,
    ADD COLUMN engine_number  VARCHAR(20) NOT NULL,
    ADD COLUMN chassis_number VARCHAR(17) NOT NULL;

CREATE INDEX idx_insured_vehicle_license_plate ON insured_vehicle (license_plate);

-- Last correlative policy number issued per year, like quotation_code_counter.
CREATE TABLE policy_number_counter (
    year        INTEGER PRIMARY KEY,
    last_value  BIGINT  NOT NULL,
    CONSTRAINT ck_policy_number_counter_last_value CHECK (last_value > 0)
);

-- number: 'AU-' || issue year || '-' || number padded to 7 digits, e.g. AU-2026-0000123.
-- Covers [valid_from, valid_to): valid_to is valid_from plus one year.
-- payment_option: the selected payment option of the quoted plan (see quotation_plan.payment_options).
CREATE TABLE policy (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    number              VARCHAR(20) NOT NULL,
    insured_id          BIGINT      NOT NULL,
    insured_vehicle_id  BIGINT      NOT NULL,
    quotation_plan_id   BIGINT      NOT NULL,
    locality_id         BIGINT      NOT NULL,
    valid_from          DATE        NOT NULL,
    valid_to            DATE        NOT NULL,
    payment_option      JSONB       NOT NULL,
    payment_method      VARCHAR(10) NOT NULL,
    version             BIGINT      NOT NULL DEFAULT 0,
    created_at          TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at          TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_policy_number UNIQUE (number),
    CONSTRAINT uk_policy_quotation_plan UNIQUE (quotation_plan_id),
    CONSTRAINT ck_policy_period CHECK (valid_to > valid_from),
    CONSTRAINT ck_policy_payment_method CHECK (payment_method IN ('CARD', 'CBU')),
    CONSTRAINT fk_policy_insured FOREIGN KEY (insured_id) REFERENCES insured (id) ON DELETE RESTRICT,
    CONSTRAINT fk_policy_insured_vehicle
        FOREIGN KEY (insured_vehicle_id) REFERENCES insured_vehicle (id) ON DELETE RESTRICT,
    CONSTRAINT fk_policy_quotation_plan
        FOREIGN KEY (quotation_plan_id) REFERENCES quotation_plan (id) ON DELETE RESTRICT,
    CONSTRAINT fk_policy_locality FOREIGN KEY (locality_id) REFERENCES locality (id) ON DELETE RESTRICT
);

CREATE INDEX idx_policy_insured_id ON policy (insured_id);
CREATE INDEX idx_policy_insured_vehicle_id ON policy (insured_vehicle_id);
CREATE INDEX idx_policy_locality_id ON policy (locality_id);
